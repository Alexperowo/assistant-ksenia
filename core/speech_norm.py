"""Сокращения и единицы — в слова перед озвучкой.

Голос (Fish S2) читает «до н. э.», «°C», «м/с», «мм», «мм рт. ст.» неправильно (проверка на слух 2026-10-09,
номера 6–8 и 11–16 списка). Здесь они разворачиваются в слова с согласованием по числу:
«4 м/с» -> «4 метра в секунду», «−3°» -> «минус 3 градуса», «44 г. до н. э.» -> «44 года до нашей эры».
Проценты, «км/ч», римские цифры голос читает сам — их не трогаем.
"""
import re


def plural(num: str, one: str, few: str, many: str) -> str:
    """Форма слова после числа: 1 градус, 2 градуса, 5 градусов; дробное — «градуса»."""
    if re.search(r"[.,]\d", num):
        return few
    n = int(re.sub(r"\D", "", num) or 0)
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


NUM = r"(\d+(?:[.,]\d+)?)"
UNITS = [
    # (шаблон после числа, формы)
    (r"мм\s?рт\.?\s?ст\.?", ("миллиметр ртутного столба", "миллиметра ртутного столба", "миллиметров ртутного столба")),
    (r"м/с", ("метр в секунду", "метра в секунду", "метров в секунду")),
    (r"мм(?![\w/])", ("миллиметр", "миллиметра", "миллиметров")),
    (r"см(?![\w/])", ("сантиметр", "сантиметра", "сантиметров")),
    (r"кг(?![\w/])", ("килограмм", "килограмма", "килограммов")),
    (r"гПа(?![\w/])", ("гектопаскаль", "гектопаскаля", "гектопаскалей")),
]
BARE = [  # единица без числа: «в м/с», «давление в мм рт. ст.»
    (r"(?<![\w/])мм\s?рт\.?\s?ст\.?", "миллиметров ртутного столба"),
    (r"(?<![\w/])м/с(?![\w/])", "метров в секунду"),
]


def _genitive(num, forms):
    """После «около/до/от…»: 1 и дробные — «миллиметра», остальные — «миллиметров»."""
    return forms[1] if plural(num, 1, 2, 3) == 1 or re.search(r"[.,]\d", num) else forms[2]


def _degrees(m):
    sign, num = m.group(1) or "", m.group(2)
    word = {"+": "плюс ", "−": "минус ", "-": "минус ", "–": "минус "}.get(sign, "")
    return f"{word}{num} {plural(num, 'градус', 'градуса', 'градусов')}"


# Ударения: голос понимает знак ударения над гласной (U+0301) — проверено на слух 2026-10-09 («звони́т», «то́рты»);
# «+» перед гласной его сбивает, заглавная гласная — не всегда. Только слова, где голос ошибается или может ошибиться.
A = "\u0301"
STRESS_WORDS = """
звони'т звоня'т звони'шь звони'м звони'те позвони'т позвоня'т позвони'шь перезвони'т созвони'мся
краси'вее краси'вейший то'рты то'ртов то'ртами догово'р догово'ры догово'ра догово'ров
катало'г катало'га кварта'л кварта'ла жалюзи' щаве'ль ба'нты ба'нтов сре'дства сре'дствами
включи'т включи'шь включи'м включа'т облегчи'ть облегчи'т ку'хонный ку'хонная ку'хонные
по'нял поняла' по'няли при'нял приняла' на'чал на'чали за'нял заняла' со'здал создала'
мусоропрово'д газопрово'д водопрово'д нефтепрово'д ото'бранный
""".split()
STRESS = {w.replace("'", ""): w.replace("'", A) for w in STRESS_WORDS}


def _stress(t: str) -> str:
    def rep(m):
        word = m.group(0)
        acc = STRESS.get(word.lower())
        if not acc:
            return word
        return acc[0].upper() + acc[1:] if word[0].isupper() else acc
    return re.sub(r"[А-Яа-яЁё]+", rep, t)


def normalize(text: str) -> str:
    t = _stress(text)
    # эры и годы
    # точка сокращения в конце предложения — она же конец фразы: сохраняем, иначе голос не делает паузу
    def era(m):
        rest = m.string[m.end():]
        return "нашей эры" + ("." if re.match(r"\s*$|\s+[А-ЯЁA-Z\d«\"]", rest) else "")
    t = re.sub(r"(?<![\w.])н\.\s?э\.", era, t)
    t = re.sub(r"\b(в|В)\s+(\d{1,4})\s?гг?\.(?=[\s,;)]|$)", r"\1 \2 году", t)
    t = re.sub(r"\b(\d{1,4})\s?гг\.(?=[\s,;)]|$)", r"\1 годов", t)
    # «2026 г.» — года; «5 г. сахара» — граммы: годом считаем только 3–4 цифры (аудит Fable, B5)
    t = re.sub(r"\b(\d{3,4})\s?г\.(?=[\s,;)]|$)", r"\1 года", t)
    t = re.sub(r"\b(\d{1,2})\s?г\.(?=[\s,;)]|$)", lambda m: f"{m.group(1)} {plural(m.group(1), 'грамм', 'грамма', 'граммов')}", t)
    # градусы: «+9°C», «−3°», «12 °С», ««+14»»
    t = re.sub(r"(?:(?<=[\s(«\"…])|^)([+−\-–])?\s?" + NUM + r"\s?°\s?[CС]?(?![\w])", _degrees, t)
    # диапазоны: «12-14°» — «°» оставался после второго числа (аудит Fable, B5); дефис между числами — не минус
    t = re.sub(r"(?<=\d)([\-–])" + NUM + r"\s?°\s?[CС]?(?![\w])",
               lambda m: f"{m.group(1)}{m.group(2)} {plural(m.group(2), 'градус', 'градуса', 'градусов')}", t)
    # единицы после числа
    for pat, forms in UNITS:
        # после «около», «до», «от», «более»… — родительный падеж: «около 2 миллиметров», а не «миллиметра»
        t = re.sub(r"(?i)\b(около|до|от|более|менее|больше|меньше|свыше|порядка)\s+" + NUM + r"\s?" + pat,
                   lambda m: f"{m.group(1)} {m.group(2)} {_genitive(m.group(2), forms)}", t)
        t = re.sub(NUM + r"\s?" + pat, lambda m: f"{m.group(1)} {plural(m.group(1), *forms)}", t)
    for pat, word in BARE:
        t = re.sub(pat, word, t)
    # знак перед числом: «как +6», «до −5»
    t = re.sub(r"(?:(?<=[\s(«\"…])|^)\+(?=\d)", "плюс ", t)
    t = re.sub(r"(?:(?<=[\s(«\"…])|^)[−\-–](?=\d)", "минус ", t)
    return t
