"""Сокращения и единицы словами — по проверке на слух 2026-10-09 (номера 6–8, 11–16)."""
import core
import speech_norm as sn


def test_era_and_years():
    assert sn.normalize("Цезарь родился в 100 году до н. э.") == "Цезарь родился в 100 году до нашей эры."
    assert sn.normalize("Это было в 44 г. до н. э. Потом") == "Это было в 44 году до нашей эры. Потом"
    assert sn.normalize("Около 2500 до н. э. империя росла") == "Около 2500 до нашей эры империя росла"
    assert sn.normalize("В 1977 г. запустили") == "В 1977 году запустили"


def test_weather_units():
    assert sn.normalize("Сейчас +9°C, ощущается как +6.") == "Сейчас плюс 9 градусов, ощущается как плюс 6."
    assert sn.normalize("Ночью −3°, днём до +12.") == "Ночью минус 3 градуса, днём до плюс 12."
    assert sn.normalize("Ветер 4 м/с, порывы до 9 м/с.") == "Ветер 4 метра в секунду, порывы до 9 метров в секунду."
    assert sn.normalize("Осадки около 2 мм.") == "Осадки около 2 миллиметров."
    assert sn.normalize("Давление 745 мм рт. ст.") == "Давление 745 миллиметров ртутного столба"
    assert sn.normalize("21 °C и 1 мм") == "21 градус и 1 миллиметр"


def test_left_alone():
    for t in ("Влажность 86%.", "Скорость 60 км/ч.", "Птолемей XIV", "с 2500-610 года", "г. Москва"):
        assert sn.normalize(t) == t


def test_in_clean_for_speech():
    assert core.clean_for_speech("Ветер 4 м/с.") == "Ветер 4 метра в секунду."


def test_stress_marks_on_trap_words():
    assert sn.normalize("Он звонит. Торты красивее, договор.") == "Он звони́т. То́рты краси́вее, догово́р."
    assert sn.normalize("Луна и зенит") == "Луна и зенит"  # прочитаны правильно — не трогаем
