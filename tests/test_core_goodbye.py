"""Конец разговора: прощание и только оно."""
import pytest

import core


@pytest.mark.parametrize("text", [
    "Пока", "пока!", "Пока, Ксения", "Ну всё, пока.", "Спасибо, пока", "Хватит", "хватит на сегодня",
    "Стоп", "Ксения, стоп", "До свидания", "Отбой", "Спокойной ночи", "Спокойной ночи, Ксения!",
    "Всё, спасибо", "все спасибо", "стоп разговор",
])
def test_goodbye(text):
    assert core.is_goodbye(text)


@pytest.mark.parametrize("text", [
    "Покажи, что на экране",          # «покажи» начинается с «пока»
    "Покачай меня на волнах музыки",
    "Пока я готовлю, включи музыку",  # «пока» как союз
    "Хватит болтать, включи лучше джаз погромче",
    "Расскажи что-нибудь", "", "   ", "Как дела?", "Стопка книг на столе",
])
def test_not_goodbye(text):
    assert not core.is_goodbye(text)
